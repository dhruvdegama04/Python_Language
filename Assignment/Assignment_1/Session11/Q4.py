"""4.Given a dictionary called food_order = {'Pizza': 2, 'Burger': 1, 'Fries': 3}, use the 
keys(), values(), and items() methods to print: a) all food items, b) all quantities, 
and c) each item with its quantity."""


food_order = {'Pizza': 2, 'Burger': 1, 'Fries': 3}

print(food_order.keys())
print(food_order.values())
print(food_order.items())