"""2.Create a small program that takes two numbers as input (use input()), 
converts them to integers using int(), and prints their sum, difference, product, 
and quotient using print().<br><br><em><strong>Hint:</strong> Remember to convert the 
input strings to integers before performing arithmetic operations.</em>"""

num1 = int(input("Enter the first number: "))
num2 = int(input("Enter the second number: "))

print(f"Sum: {num1 + num2}")
print(f"Difference: {num1 - num2}")
print(f"Product: {num1 * num2}")
print(f"Quotient: {num1 / num2}")

