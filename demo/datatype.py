#int

a=123
print("value is",a,type(a))

#float

b=22.22
print("float value is",b,type(b))

#complex

c=5+3j
print("complex value is",c,type(c))

#string

d='dhruv'
print("my name is",d,type(d))

#list

e=[1,2,"dhruv",50.55]
print("list value is",e,type(e))

#tuple
f=(1,2,"dhruv",50.55)
print("tuple value is",f,type(f))

#map - dictonary

g={"dhruv":"prajapati"}
print("map value is",g,type(g))

#range

h=range(10)
print("range is",h,type(h))

#bool

i=True
print("This value is",i,type(i))

